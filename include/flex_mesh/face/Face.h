	template<typename NodeType>
	class Face
	{
	public:
		typedef FaceType* FacePtr;
		typedef EdgeType* EdgePtr;
		typedef NodeType* NodePtr;
		typedef uint8_t ConnSize;

		/// Note: you can also use initializer lists here, such as:
		/// Face<Node> e(FaceType::L2D2N, { &n1, &n2 }); // n1 and n2 are Node objects
		Face(const FaceType& geom_type, const Connectivity<NodeType, ConnSize>& connectivity);
		virtual ~Face() {};

		/// Get the type by const-ref
		const FaceType& get_type() const;
		/// Returns an identifier that is unique to faces that have the same connectivity
		const std::size_t& get_conn_hash_id() const;
		/// Returns vector that is mean coordinate of the nodes defining this face
		Point get_mean_coordinate() const;


		/// Returns a vector of edges for the face.  The order of the edges will correspond
		/// to the order generated by get_edge_info.
		std::vector<Edge<const NodeType>> get_edges() const;
		/// Returns a vector of shared pointers that will last as long as something
		/// references them.  It is helpful when accummulating edges in an algorithm.
		std::vector<std::shared_ptr<Edge<const NodeType>>> get_edges_shared_ptrs() const;


		/// Returns the vector defining the outward normal.
		/// Kind of a hack right now, but works for all the elements in BetaMesh currently,
		/// revisit this if new types are added.
		Vector3D get_outward_normal() const;
		/// Given a point this will calculate the signed normal projection to the point
		/// In other words, it is the distance to the point in the direction of the face
		/// normal axis.  Positive values indicate it is the in outward direction of the face
		/// while negative values indicate it is in the inward direction.
		double calc_signed_norm_projection(const Point& point) const;

		/// If the face is quadratic, modify the connectivity and FaceGeomType to make this
		/// a linear version of the quadratic face.  If it is linear already, this does nothing.
		void make_linear();

		/// Returns the node pointer at the beginning of the connectivity
		auto begin() const;
		/// Returns the node pointer at the end of the connectivity
		auto end() const;

		/// Compares based on mean coordinate of the two edges (takes into account tolerance)
		bool operator < (const Face &Other) const;
		/// Compares based on mean coordinate of the two edges (takes into account tolerance)
		bool operator > (const Face &Other) const;

	private:
		/// The geometry/topolgoy type of edge (determines the number of nodes)
		FaceType type_;
		/// The ordered list of nodes defining the edge.
		/// NOTE: this object does not own the nodes and will not delete them
		Connectivity<NodeType, ConnSize> connectivity_;
		/// An identifier that will match any other faces that have the exact same connectivity
		/// This is generated when the face is created
		std::size_t conn_hash_id_;
	};

	/////////////////
	// Definitions //
	/////////////////

	template<typename NodeType>
	inline Face<NodeType>::Face(const FaceType & geom_type, const Connectivity<NodeType, ConnSize> & connectivity)
		: type_(geom_type), connectivity_(connectivity), conn_hash_id_(0)
	{
		assert(connectivity_.size() == get_num_nodes_for_type(type_));
		update_conn_hash_id();
	}

	template<typename NodeType>
	inline const FaceType & Face<NodeType>::get_type() const
	{
		return type_;
	}

	template<typename NodeType>
	inline const std::size_t & Face<NodeType>::get_conn_hash_id() const
	{
		return conn_hash_id_;
	}

	template<typename NodeType>
	inline Point Face<NodeType>::get_mean_coordinate() const
	{
		return get_mean_coordinate_of_nodes(connectivity_);
	}

	template<typename NodeType>
	inline std::vector<Edge<const NodeType>> Face<NodeType>::get_edges() const
	{
		auto edge_info = get_edge_info(type_);

		std::vector<Edge<const NodeType>> edges;
		for (auto i = 0; i < edge_info.size(); i++)
        {
			std::vector<const NodeType*> edge_nodes;
            for (auto node_index : edge_info[i].connectivity)
            {
                edge_nodes.push_back(connectivity_[node_index]);
            }
			edges.push_back(Edge<const NodeType>(edge_info[i].type, edge_nodes));
		}
		return edges;
	}

	template<typename NodeType>
	inline std::vector<std::shared_ptr<Edge<const NodeType>>> flex_mesh::Face<NodeType>::get_edges_shared_ptrs() const
	{
		auto edge_info = get_edge_info(type_);

		std::vector<std::shared_ptr<Edge<const NodeType>>> edges;
		for (auto i = 0; i < edge_info.size(); i++)
        {
			std::vector<const NodeType*> edge_nodes;
            for (auto node_index : edge_info[i].connectivity)
            {
                edge_nodes.push_back(connectivity_[node_index]);
            }
			edges.push_back(std::make_shared<Edge<const NodeType>>(edge_info[i].type, edge_nodes));
		}
		return edges;
	}

	template<typename NodeType>
	inline Vector3D Face<NodeType>::get_outward_normal() const
	{
		const Point centroid = get_mean_coordinate();
		const Vector3D centroidVec = point_as_vector(centroid);
		const Vector3D vec1 = connectivity_[1]->as_eigen_vec3d() - connectivity_[0]->as_eigen_vec3d();
		const Vector3D vec2 = centroidVec - connectivity_[0]->as_eigen_vec3d();
		Vector3D normalVec = vec1.cross(vec2).normalized();
		normalVec.normalize();
		return normalVec;
	}

	template<typename NodeType>
	inline double Face<NodeType>::calc_signed_norm_projection(const Point & point) const
	{
		// This is kind of a hack but it works for all the elements at the moment
		// but for the types we have the normal vector can be found by crossing these two
		// in-plane vectors with each other:
		// vec 1: the first node in the connectivity to the second node
		// vec 2: the first node in the connectivity to the last node
		// I cannot imagine a situation where this would not work, but revaulate if it ever occurs.
		const Point centroid = get_mean_coordinate();
		const Vector3D centroidVec = point_as_vector(centroid);
		const Vector3D vec1 = connectivity_[1]->as_eigen_vec3d() - connectivity_[0]->as_eigen_vec3d();
		const Vector3D vec2 = connectivity_.back()->as_eigen_vec3d() - connectivity_[0]->as_eigen_vec3d();
		const Vector3D normalVec = vec1.cross(vec2).normalized();
		// Center the point relative to the centroid so we get an accurate measure of direction
		const Vector3D pointCentered = point_as_vector(point) - centroidVec;
		double projection = pointCentered.dot(normalVec);
		return projection;
	}

	template<typename NodeType>
	inline void Face<NodeType>::make_linear()
	{
		auto linear_type = get_linearized_type(type_);
		auto linear_permute = get_linearized_permutation(type_);
		// Convert type and connectivity
		type_ = linear_type;

		std::vector<NodeType*> new_nodes(linear_permute.size());
		for (auto i = 0; i < new_nodes.size(); i++)
			new_nodes[i] = connectivity_[linear_permute[i]];
		connectivity_ = new_nodes;
	}

	template<typename NodeType>
	inline auto Face<NodeType>::begin() const
	{
		return connectivity_.begin();
	}

	template<typename NodeType>
	inline auto Face<NodeType>::end() const
	{
		return connectivity_.end();
	}

	template<typename NodeType>
	inline bool Face<NodeType>::operator<(const Face & other) const
	{
		return compare_points(get_mean_coordinate(), other.get_mean_coordinate(), NodeType::get_compare_tolerance());
	}

	template<typename NodeType>
	inline bool Face<NodeType>::operator>(const Face & other) const
	{
		return compare_points(other.get_mean_coordinate(), get_mean_coordinate(), NodeType::get_compare_tolerance());
	}

