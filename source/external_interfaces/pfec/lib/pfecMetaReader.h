#pragma once

#include "pfecBaseReader.h"
#include "pfecMeshReader.h"
#include "pfecDataReader.h"
#include "pfecGroupReader.h"

#include <memory>
#include <set>

namespace PFECNativeInterface {

	/// This is a struct used to describe a time step.
	struct TimeStepMeta {
		int time_step_id_;
		double time_value_;
		std::string mesh_file_path_;
		std::string orient_file_path_;
		std::string data_file_path_;
		std::vector<DataType> data_types_;
		std::vector<std::string> data_names_;
		std::vector<std::string> group_file_paths_;

		TimeStepMeta() {
			time_step_id_ = 0;
			time_value_ = 0.0;
		};
		/// If data_file_path_ is set, this will extract what types
		/// of data exist in the file.
		void extract_data_array_info(std::string metaFileDir);
	};

    /// This class is the reader intended to read the meta file and allow
    /// consistent access to the mesh and corresponding data without having
    /// to know about how the files are stored.
    /// Note: use the is_mesh_time_dependent method to know if you need
    /// to read the mesh every time step, or if you can save time by just
    /// reading the mesh for the first time step and reuse it for all time
    /// steps.
    ///
    /// Example:
    /// <code>
    /// PFECNativeInterface::MetaReader execReader;
    /// execReader.read_meta_file("C:/metaFile.bfx");
    /// std::vector<int> outputTimeIDs = execReader.get_output_time_step_ids();
    /// for (auto timeID : outputTimeIDs) {
    ///     auto meshReaderPtr = execReader.get_mesh_reader(timeID);
    ///     // Do something with the mesh reader, such as reading the node and
    ///     // element information to plot or display.
    ///     // Example for getting the partitions in the file:
    ///     auto partsInFile = meshReaderPtr->get_parts_in_file();
    /// }
    /// </code>
    class MetaReader
    {
    public:
		MetaReader() : mesh_is_time_dependent_(false) {};
		MetaReader(const std::string filePath) { read_meta_file(filePath); };
        /// Reads the meta file generated by an analysis
        /// This will point to the neccessary mesh, data, and group file
        void read_meta_file(std::string filePath);
		/// Returns the directory of the meta file
		std::string get_meta_dir() const { return meta_file_dir_; };
        /// Get the number of time steps
        int get_num_time_steps() { return static_cast<int>(time_step_id_map_.size()); };
        /// Get the time steps that have data
        std::vector<int> get_output_time_step_ids();
        /// Get the time step values that have data
        std::vector<double> get_output_time_step_vals();
        /// Get the bool indicating if the mesh is time dependant
        bool is_mesh_time_dependent() { return mesh_is_time_dependent_; };
        /// Returns a unique pointer to a mesh reader object for the specified time step
        std::unique_ptr<PFECNativeInterface::MeshReader> get_mesh_reader(int timeStepID);
        /// Returns a unique pointer to a data reader object that points to orientation data for the specified time step
        std::unique_ptr<PFECNativeInterface::DataReader> get_orient_reader(int timeStepID);
        /// Returns a unique pointer to a data reader object for the specified time step
        std::unique_ptr<PFECNativeInterface::DataReader> get_data_reader(int timeStepID);
        /// Returns the file paths to all the group readers
        std::vector<std::string> get_group_file_paths(int timeStepID);
		/// Returns the first mesh file path
		std::string get_initial_mesh_path() { return time_step_metas_.front().mesh_file_path_; }
		/// Returns the first orientation file path
		std::string get_initial_orient_path() { return time_step_metas_.front().orient_file_path_; }
		/// Returns the path to the meta file this reader points to
		std::string get_meta_filepath() const { return meta_filepath_; }
		/// Returns the data type - name pairs that exist for every time step in the analysis (intersection of data outputs)
		std::set<std::pair<PFECNativeInterface::DataType, std::string>> get_common_data_outputs() const;

    protected:
        /// The name of the analysis
        std::string analysis_name_;
        /// A convenient map of id to index of the meta info for the time step
        std::map<int, size_t> time_step_id_map_;
		/// The vector of time step meta data
		std::vector<TimeStepMeta> time_step_metas_;
        /// Indicates if the mesh is time dependant.  If true, then the
        /// mesh_file_paths_ vector will contain a value for each time step.
        bool mesh_is_time_dependent_;
		/// The filepath to the meta file
		std::string meta_filepath_;
        /// The paths stored in the paths are all relative to the meta file, so
        /// this stores the directory path where the meta file exists
        std::string meta_file_dir_;

		virtual void clear();
    };

};