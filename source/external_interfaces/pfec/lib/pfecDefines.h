    /// Developer note: I have disable size_t to PFEC_INT conversion warnings in VS
    /// since I can guarantee no loss of data (as the library is reading and writing
    /// the data).

    /// Note: this needs be thought of carefully and here is why:
    /// - Standard containers (std containers) can accept indices of size
    ///   size_t, which is platform dependant.  On 64-bit Windows, it is
    ///   actually a 64 unsigned integral value, which is huge.
    ///   However, if you use size_t, then a mesh output on 64-bit windows
    ///   could not be read by the same library compiled on 32-bit windows
    ///   since size_t is actually a 32-bit unsigned integral type.
    /// - unsigned long seems to behave as expected for the platforms we
    ///   are interested in, but we are limiting the indexing to 32-bit
    ///   unsigned integral types or about 4.3 billion.  Now, I do not
    ///   think we will exceed that size in the near future, but if we do
    ///   then I would suggest just giving a strong type like uint64.
    ///   However, there is one issue to worry about, meshes that large
    ///   could not be generated on a 32-bit machine without the use
    ///   of a non-standard container class.
    /// Note: I went ahead and moved to uint64_t, thought I left the
    /// explanation above to explain why I did this.
	/// Appropriate for global numbering/indices
    typedef uint64_t PFEC_IND;
	/// The type to be used for shorter lists, appropriate for partition numbering
	typedef int32_t PFEC_INT;
	/// The unsigned type for shorter values, appropriate for partition numbering
	typedef uint32_t PFEC_UINT;

