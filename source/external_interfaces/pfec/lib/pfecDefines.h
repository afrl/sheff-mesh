	/// A concise container for node information
	struct NodeInfo
	{
		std::vector<PFEC_IND> nodeIndices;
		std::vector<PFEC_INT> partitions;
		std::vector< std::vector<double> > coords;

		void copy_subset(const NodeInfo& other, const std::vector<unsigned int> & otherInds) {
			resize(otherInds.size());
			for (auto i = 0; i < otherInds.size(); i++) {
				auto otherInd = otherInds[i];
				nodeIndices[i] = other.nodeIndices[otherInd];
				partitions[i] = other.partitions[otherInd];
				coords[i] = other.coords[otherInd];
			}
		}

		void resize(std::size_t s) {
			nodeIndices.resize(s);
			partitions.resize(s);
			coords.resize(s);
		}

		void clear() {
			nodeIndices.clear();
			partitions.clear();
			coords.clear();
		}
	};

	/// A concise container for element information
	struct ElementInfo
	{
		std::vector<PFEC_IND> globalIndices;
		std::vector<PFEC_INT> partitions;
		std::vector<PFEC_INT> domains;
		std::vector<ElemGeomType> elemGeomTypes;
		std::vector< std::vector<PFEC_INT>> localConnectivity;

		void copy_subset(const ElementInfo & other,
			const std::vector<unsigned int> & otherInds,
			const std::map<unsigned int, unsigned int> & localIndexMap)
		{
			resize(otherInds.size());
			for (auto i = 0; i < otherInds.size(); i++) {
				auto otherInd = otherInds[i];
				globalIndices[i] = other.globalIndices[otherInd];
				partitions[i] = other.partitions[otherInd];
				domains[i] = other.domains[otherInd];
				elemGeomTypes[i] = other.elemGeomTypes[otherInd];
				localConnectivity[i] = other.localConnectivity[otherInd];
				for (auto& c : localConnectivity[i]) c = localIndexMap.find(c)->second;
			}
		}

		void resize(std::size_t s) {
			globalIndices.resize(s);
			partitions.resize(s);
			domains.resize(s);
			elemGeomTypes.resize(s);
			localConnectivity.resize(s);
		}

		void clear() {
			globalIndices.clear();
			partitions.clear();
			domains.clear();
			elemGeomTypes.clear();
			localConnectivity.clear();
		}
	};

    /// \brief A simple struct container for the metadata for the data (confusing terminology, I know).
    ///
    /// - id: each data block (a particular data set to write, such as displacements or stresses) must have
    ///       a unique id, but does not neccessarily need to be contiguous or start at 0.
    /// - type: the types each data block, see DataType in the Defines.h file.
    /// - num_comps: the number of components at the node/element/quadpoint.  Use 0 for data that is a consistent
    ///              type whith which you do not have a desire to visualize it.  For example, for dumping the ISV
    ///              data to be used for restarting if needed, use 0 for the number of components.
    /// - name: a friendly name (short) to be used during visualization.  I suggest sticking to some standard
    ///         format.  (Displacement, Stress, Strain, DamageFactor, etc.).  Though you have quad point data
    ///         and name it, it will not be used for visualization. (Use CapitalizeEachWord format and use
    ///         singular form)
    /// - comp_names: a vector of names for each component of data, see name for guidelines
    struct DataMetaData {
		DataMetaData() = default;
        DataMetaData(const PFEC_INT &id_a, const DataType &type_a, const PFEC_INT &num_comps_a,
            const std::string &name_a, const std::vector<std::string> &comp_names_a) :
            id(id_a), type(type_a), num_comps(num_comps_a), name(name_a) {
            comp_names = comp_names_a;
        };
		DataMetaData(const DataMetaData&) = default;
		DataMetaData(DataMetaData&&) = default;
		DataMetaData& operator = (const DataMetaData&) = default;

		bool operator == (const DataMetaData& other) {
			if (this->id != other.id) return false;
			if (this->type != other.type) return false;
			if (this->num_comps != other.num_comps) return false;
			if (this->name != other.name) return false;
			if (this->comp_names.size() != other.comp_names.size()) return false;
			return true;
		}
		bool operator != (const DataMetaData& other) {
			return !(*this == other);
		}

        PFEC_INT id;
        DataType type;
        PFEC_INT num_comps;
        std::string name;
        std::vector<std::string> comp_names;
    };
